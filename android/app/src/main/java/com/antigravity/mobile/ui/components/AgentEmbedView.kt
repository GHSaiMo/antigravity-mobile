                isLoading = false
                val content = if (respStr.trim().startsWith("{") && respStr.contains("\"content\":")) {
                    val jsonObj = org.json.JSONObject(respStr)
                    jsonObj.optString("content", respStr)
                } else {
                    respStr
                }
                AgentEmbedCache.put(src, content)
                htmlContent = content
                errorMessage = null
            } catch (e: Exception) {
                isLoading = false
                errorMessage = e.localizedMessage ?: "网络异常".loc
            }
        } else {
            isLoading = false
            errorMessage = "未配置网关连接".loc
        }
    }

