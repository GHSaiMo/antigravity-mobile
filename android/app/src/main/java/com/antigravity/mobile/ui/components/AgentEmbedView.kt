                    modifier = Modifier.size(13.dp)
                )

                Text(
                    text = detectedTitle ?: defaultTitle,
                    color = colors.textPrimary,
                    fontSize = 12.sp,
                    fontWeight = FontWeight.SemiBold,
                    maxLines = 1
                )

                Box(
                    modifier = Modifier
                        .clip(CircleShape)
                        .background(colors.accentIndigo.copy(alpha = 0.12f))
                        .padding(horizontal = 5.dp, vertical = 1.5.dp)
                ) {
                    Text(
                        text = "INTERACTIVE",
                        color = colors.accentIndigo,
                        fontSize = 9.5.sp,
                        fontWeight = FontWeight.Bold,
                        fontFamily = FontFamily.Monospace
                    )
                }
            }

            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                // Refresh Button
                IconButton(
                    onClick = {
                        haptic.light()
                        AgentEmbedCache.remove(src)
                        reloadTrigger++
                    },
                    modifier = Modifier.size(24.dp)
                ) {
                    Icon(
                        imageVector = Icons.Default.Refresh,
                        contentDescription = "刷新".loc,
                        tint = colors.textSecondary,
                        modifier = Modifier.size(14.dp)
                    )
                }

                // Fullscreen Button
                if (htmlContent != null && errorMessage == null) {
                    IconButton(
                        onClick = {
                            haptic.light()
                            isFullscreen = true
                        },
                        modifier = Modifier.size(24.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.Fullscreen,
                            contentDescription = "全屏查看".loc,
                            tint = colors.textSecondary,
                            modifier = Modifier.size(16.dp)
                        )
                    }
                }
            }
        }

        HorizontalDivider(color = colors.border.copy(alpha = 0.35f), thickness = 0.6.dp)

        // Main Content Area
        Box(
            modifier = Modifier.fillMaxWidth(),
            contentAlignment = Alignment.BottomEnd
        ) {
            when {
                errorMessage != null -> {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(140.dp)
                            .padding(16.dp),
                        verticalArrangement = Arrangement.Center,
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.Warning,
                                contentDescription = null,
                                tint = Color(0xFFFF9800),
                                modifier = Modifier.size(15.dp)
                            )
                            Text(
                                text = "交互卡片加载失败".loc,
                                color = colors.textPrimary,
                                fontSize = 12.5.sp,
                                fontWeight = FontWeight.SemiBold
                            )
                        }

                        Spacer(modifier = Modifier.height(4.dp))

                        Text(
                            text = errorMessage ?: "未知错误".loc,
                            color = colors.textSecondary,
                            fontSize = 11.sp,
                            maxLines = 2
                        )

                        Spacer(modifier = Modifier.height(8.dp))

                        Button(
                            onClick = {
                                AgentEmbedCache.remove(src)
                                reloadTrigger++
                            },
                            contentPadding = PaddingValues(horizontal = 14.dp, vertical = 4.dp),
                            shape = CircleShape,
                            colors = ButtonDefaults.buttonColors(
                                containerColor = colors.accentIndigo.copy(alpha = 0.15f),
                                contentColor = colors.accentIndigo
                            ),
                            modifier = Modifier.height(30.dp)
                        ) {
                            Text(text = "重试".loc, fontSize = 11.sp, fontWeight = FontWeight.Medium)
                        }
                    }
                }

                htmlContent != null -> {
                    AgentEmbedWebViewContainer(
                        htmlContent = htmlContent!!,
                        isDark = isDark,
                        embedSrc = src,
                        boundCascadeId = hostCascadeId,
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(embedHeightDp),
                        onHeightMeasured = { hCssPx ->
                            val dpVal = hCssPx.dp
                            embedHeightDp = dpVal.coerceIn(160.dp, 520.dp)
                        },
                        onTitleDetected = { t ->
                            if (detectedTitle == null && t.isNotBlank()) {
                                detectedTitle = t
                            }
                        }
                    )

                    // Subtle hint pill for full-screen expanded action if large
                    if (embedHeightDp >= 480.dp) {
                        Row(
                            modifier = Modifier
                                .padding(8.dp)
                                .clip(CircleShape)
                                .background(colors.surface.copy(alpha = 0.88f))
                                .border(0.5.dp, colors.border.copy(alpha = 0.5f), CircleShape)
                                .clickable {
                                    haptic.light()
                                    isFullscreen = true
                                }
                                .padding(horizontal = 8.dp, vertical = 3.5.dp),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(4.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.Fullscreen,
                                contentDescription = null,
                                tint = colors.textMuted,
                                modifier = Modifier.size(11.dp)
                            )
                            Text(
                                text = "全屏操作".loc,
                                color = colors.textSecondary,
                                fontSize = 10.sp,
                                fontWeight = FontWeight.Medium
                            )
                        }
                    }
                }

                else -> {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(160.dp),
                        verticalArrangement = Arrangement.Center,
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        CircularProgressIndicator(
                            color = colors.accentIndigo,
                            strokeWidth = 2.dp,
                            modifier = Modifier.size(24.dp)
                        )
                        Spacer(modifier = Modifier.height(8.dp))
                        Text(
                            text = "正在加载交互组件...".loc,
                            color = colors.textSecondary,
                            fontSize = 11.sp
