    /**
     * Resolves the asset image name for a given file name, path, or URL (1:1 with iOS FileIconResolver.resolveIcon).
     */
    fun resolveIcon(pathOrName: String): String? {
        var str = pathOrName.trim().trim('`', '\'', '"')
        if (str.isEmpty()) return null

        // Strip URL scheme if present (e.g. file:///path/to/file.go -> /path/to/file.go)
        if (str.startsWith("file://")) {
            str = str.removePrefix("file://")
        } else {
            val match = urlSchemeRegex.find(str)
            if (match != null) {
                str = str.substring(match.range.last + 1)
            }
        }

        // Strip URL fragments (#L173-L179, #anchor)
        if (str.contains('#')) {
            str = str.substringBefore('#')
        }

        // Strip URL query parameters (?foo=bar)
        if (str.contains('?')) {
            str = str.substringBefore('?')
        }

        // Strip trailing line/column specifiers (e.g. :123, :123:45, :L123-L145)
        str = str.replace(lineSuffixRegex, "")
        str = str.trim().trim('`', '\'', '"', ' ', '\t', '\n', '\r')
        if (str.isEmpty()) return null

        val fileName = str.substringAfterLast('/').lowercase()
        fileNames[fileName]?.let { return it }

        val ext = if (fileName.contains('.')) fileName.substringAfterLast('.') else ""
        if (ext.isNotEmpty()) {
            fileExtensions[ext]?.let { return it }
        }

        return null
    }

    /**
     * Checks whether a file path or URL represents a script/source code file.
     * These files do not need to be accessible/previewed on mobile devices.
     */
    fun isScriptFile(pathOrName: String): Boolean {
        var str = pathOrName.trim().trim('`', '\'', '"')
        if (str.isEmpty()) return false
        if (str.startsWith("file://")) str = str.removePrefix("file://")
        if (str.contains('#')) str = str.substringBefore('#')
        if (str.contains('?')) str = str.substringBefore('?')
        str = str.replace(lineSuffixRegex, "").trim()

        val fileName = str.substringAfterLast('/').lowercase()
        val ext = if (fileName.contains('.')) fileName.substringAfterLast('.') else ""
        return ext.isNotEmpty() && scriptExtensions.contains(ext)
    }

    /**
     * Checks whether a file is an accessible document, presentation, sheet, or image.
     */
    fun isAccessibleDocument(pathOrName: String): Boolean {
        var str = pathOrName.trim().trim('`', '\'', '"')
        if (str.isEmpty()) return false
        val lower = str.lowercase()

        // Markdown and plan artifacts
        if (lower.endsWith(".md") || lower.endsWith(".markdown") ||
            lower.contains("/brain/") || lower.contains("/static/artifacts/") ||
            lower.contains("implementation_plan") || lower.contains("walkthrough")
        ) {
            return true
        }

        return allPreviewExtensions.any { ext ->
            lower.endsWith(ext) || lower.contains("$ext?") || lower.contains("$ext#")
        }
    }

