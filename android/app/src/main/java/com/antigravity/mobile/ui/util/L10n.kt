    fun t(chinese: String): String {
        if (!isEnglish) return chinese
        if (chinese.isEmpty()) return chinese

        // 1. 精确匹配
        val exact = dict[chinese]
        if (exact != null) return exact

        // 2. 正则模式匹配
        for (rule in patternRules) {
            val m = rule.regex.matchEntire(chinese)
            if (m != null) {
                return rule.transform(m)
            }
        }

        return chinese
    }

    fun format(chinese: String, vararg args: Any): String {
        val translated = t(chinese)
        return if (args.isNotEmpty()) {
            try {
                String.format(Locale.US, translated, *args)
            } catch (_: Exception) {
                translated
            }
        } else {
            translated
        }
    }

