    val isEnglish: Boolean
        get() = when (languagePref) {
            "en" -> true
            "zh" -> false
            else -> {
                // 跟随系统语言：只要系统当前语言不是以 zh 开头，即视为英文环境
                val lang = Locale.getDefault().language.lowercase()
                !lang.startsWith("zh")
            }
        }

