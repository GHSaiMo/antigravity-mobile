func TestTokenSignAndVerify(t *testing.T) {
	secret := "test-relay-signing-secret-2026"
	now := time.Unix(1795360000, 0)
	tok, err := SignToken(secret, TokenClaims{
		Version:   1,
		ShortID:   "a1b2c3d4",
		OwnerHash: "0123456789abcdef0123456789abcdef",
		Domain:    "r-a1b2c3d4.jiuge.space",
		Region:    "us",
		IssuedAt:  now.Unix(),
	})
	if err != nil {
		t.Fatalf("SignToken: %v", err)
	}
	if !strings.HasPrefix(tok, "mgyr1.") {
		t.Fatalf("expected mgyr1 prefix, got %q", tok)
	}

	claims, err := VerifyToken(secret, tok, now.Add(time.Minute), 0)
	if err != nil {
		t.Fatalf("VerifyToken: %v", err)
	}
	if claims.ShortID != "a1b2c3d4" || claims.Domain != "r-a1b2c3d4.jiuge.space" || claims.Region != "us" {
		t.Fatalf("unexpected claims: %+v", claims)
	}

	// Wrong secret must fail
	if _, err := VerifyToken("wrong-secret", tok, now, 0); err == nil {
		t.Fatalf("expected VerifyToken to reject wrong secret")
	}

	// Tampered payload must fail
	parts := strings.Split(tok, ".")
	tampered := parts[0] + "." + parts[1] + "A." + parts[2]
	if _, err := VerifyToken(secret, tampered, now, 0); err == nil {
		t.Fatalf("expected VerifyToken to reject tampered payload")
	}

	// Expired token must fail when maxAge > 0
	if _, err := VerifyToken(secret, tok, now.Add(2*time.Hour), time.Hour); err == nil {
		t.Fatalf("expected expired token to fail")
	}

	// Cross-language golden vector generated by scripts/cloudflare-worker/worker.js signRelayV1Token()
	jsToken := "mgyr1.eyJ2IjoxLCJzaWQiOiJjYWZlYmFiZSIsIm9oIjoiMDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWYiLCJkb20iOiJyLWNhZmViYWJlLmppdWdlLnNwYWNlIiwicmVnIjoiYXAiLCJpYXQiOjE3OTUzNjAwMDB9.emPFtvs8qhV3cl4ka_g6sJkOXc2ru7dzKUL5rl4ZwWw"
	jsClaims, err := VerifyToken("cross-lang-test-secret", jsToken, now.Add(time.Minute), time.Hour)
	if err != nil {
		t.Fatalf("cross-language JS Worker token failed VerifyToken: %v", err)
	}
	if jsClaims.ShortID != "cafebabe" || jsClaims.Domain != "r-cafebabe.jiuge.space" || jsClaims.Region != "ap" {
		t.Fatalf("unexpected cross-language claims: %+v", jsClaims)
	}
}

func TestRelayEndToEnd_HTTP_Streaming_WebSocket_And_OwnerIsolation(t *testing.T) {
	secret := "e2e-relay-secret"

	// 1. Mock local mgy gateway (HTTP JSON + streaming + WebSocket echo)
	wsUpgrader := websocket.Upgrader{CheckOrigin: func(*http.Request) bool { return true }}
	localGateway := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/healthz":
			w.Header().Set("X-Seen-Host", r.Host)
			w.Header().Set("X-Seen-Relay", r.Header.Get("X-Mgy-Relay"))
			_, _ = w.Write([]byte(`{"status":"ok","from":"local-gateway"}`))
		case "/ws/echo":
			conn, err := wsUpgrader.Upgrade(w, r, nil)
			if err != nil {
				return
			}
			defer conn.Close()
			for {
				mt, msg, err := conn.ReadMessage()
				if err != nil {
					return
				}
				if err := conn.WriteMessage(mt, append([]byte("echo:"), msg...)); err != nil {
					return
				}
			}
		default:
			http.NotFound(w, r)
		}
	}))
	defer localGateway.Close()
	localAddr := strings.TrimPrefix(localGateway.URL, "http://")

	// 2. Start mgy-relay server
	relaySrv, err := NewServer(ServerConfig{
		SigningSecret:   secret,
		ControlHosts:    []string{"relay.jiuge.space"},
		AllowedSuffixes: []string{".jiuge.space"},
	})
	if err != nil {
		t.Fatalf("NewServer: %v", err)
	}
	defer relaySrv.Close()

	relayHTTP := httptest.NewServer(relaySrv)
	defer relayHTTP.Close()

	// 3. Connect gateway client with signed mgyr1 token
	userDomain := "r-deadbeef.jiuge.space"
	tok, err := SignToken(secret, TokenClaims{
		ShortID:   "deadbeef",
		OwnerHash: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
		Domain:    userDomain,
		Region:    "us",
	})
	if err != nil {
		t.Fatalf("SignToken: %v", err)
	}

	connected := make(chan struct{}, 1)
	wsEndpoint := "ws" + strings.TrimPrefix(relayHTTP.URL, "http") + TunnelUpgradePath
	client, err := NewClient(ClientConfig{
		RelayEndpoint: wsEndpoint,
		Token:         tok,
		LocalAddr:     localAddr,
		PublicURL:     "https://" + userDomain,
		Subdomain:     userDomain,
		OnConnected: func() {
			select {
			case connected <- struct{}{}:
			default:
			}
		},
	})
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	if err := client.Start(ctx); err != nil {
		t.Fatalf("client.Start: %v", err)
	}
	defer client.Stop()

	select {
	case <-connected:
	case <-time.After(5 * time.Second):
		t.Fatalf("timed out waiting for relay client connection")
	}

	// Give server registration a brief tick
	deadline := time.Now().Add(2 * time.Second)
	for relaySrv.ActiveTunnels() < 1 && time.Now().Before(deadline) {
		time.Sleep(10 * time.Millisecond)
	}
	if relaySrv.ActiveTunnels() != 1 {
		t.Fatalf("expected 1 active tunnel, got %d", relaySrv.ActiveTunnels())
	}

	// 4. Verify control-host /healthz serves relay stats (NOT forwarded)
	ctrlReq, _ := http.NewRequest(http.MethodGet, relayHTTP.URL+"/healthz", nil)
	ctrlReq.Host = "relay.jiuge.space"
	ctrlResp, err := http.DefaultClient.Do(ctrlReq)
	if err != nil {
		t.Fatalf("control healthz: %v", err)
	}
	ctrlBody, _ := io.ReadAll(ctrlResp.Body)
	ctrlResp.Body.Close()
	if ctrlResp.StatusCode != http.StatusOK || !strings.Contains(string(ctrlBody), `"service":"mgy-relay"`) {
		t.Fatalf("unexpected control healthz: status=%d body=%s", ctrlResp.StatusCode, string(ctrlBody))
	}

	// 5. Verify user tunnel /healthz IS forwarded to local gateway
	userReq, _ := http.NewRequest(http.MethodGet, relayHTTP.URL+"/healthz", nil)
	userReq.Host = userDomain
	userResp, err := http.DefaultClient.Do(userReq)
	if err != nil {
		t.Fatalf("user healthz: %v", err)
	}
	userBody, _ := io.ReadAll(userResp.Body)
	userResp.Body.Close()
	if userResp.StatusCode != http.StatusOK || !strings.Contains(string(userBody), `"from":"local-gateway"`) {
		t.Fatalf("unexpected user healthz: status=%d body=%s", userResp.StatusCode, string(userBody))
	}
	if got := userResp.Header.Get("X-Seen-Host"); got != userDomain {
		t.Errorf("expected X-Seen-Host=%q, got %q", userDomain, got)
	}
	if got := userResp.Header.Get("X-Seen-Relay"); got != "1" {
		t.Errorf("expected X-Seen-Relay=1, got %q", got)
	}

	// 6. Verify full-duplex WebSocket over multiplexed yamux tunnel!
	wsDialHdr := http.Header{"Host": []string{userDomain}}
	wsPublicURL := "ws" + strings.TrimPrefix(relayHTTP.URL, "http") + "/ws/echo"
	pubWS, _, err := websocket.DefaultDialer.Dial(wsPublicURL, wsDialHdr)
	if err != nil {
		t.Fatalf("public WS dial through relay failed: %v", err)
	}
	defer pubWS.Close()
	if err := pubWS.WriteMessage(websocket.TextMessage, []byte("hello-multigravity")); err != nil {
		t.Fatalf("pubWS write: %v", err)
	}
	_, echoed, err := pubWS.ReadMessage()
	if err != nil {
		t.Fatalf("pubWS read: %v", err)
	}
	if string(echoed) != "echo:hello-multigravity" {
		t.Fatalf("unexpected WS echo: %q", string(echoed))
	}

	// 7. Verify attacker with different owner_hash CANNOT hijack userDomain!
	attackerTok, _ := SignToken(secret, TokenClaims{
		ShortID:   "deadbeef",
		OwnerHash: "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
		Domain:    userDomain,
	})
	_, atkResp, err := websocket.DefaultDialer.Dial(wsEndpoint, http.Header{
		"Authorization": []string{"Bearer " + attackerTok},
		"Host":          []string{"relay.jiuge.space"},
	})
	if err == nil {
		t.Fatalf("expected hijacker dial to fail")
	}
	if atkResp == nil || atkResp.StatusCode != http.StatusForbidden {
		t.Fatalf("expected 403 Forbidden for owner mismatch, got resp=%v err=%v", atkResp, err)
	}

	// 8. Verify offline domain returns 503 gateway_offline
	offReq, _ := http.NewRequest(http.MethodGet, relayHTTP.URL+"/healthz", nil)
	offReq.Host = "r-00000000.jiuge.space"
	offResp, err := http.DefaultClient.Do(offReq)
	if err != nil {
		t.Fatalf("offline req: %v", err)
	}
	offResp.Body.Close()
	if offResp.StatusCode != http.StatusServiceUnavailable {
		t.Fatalf("expected 503 for offline tunnel, got %d", offResp.StatusCode)
	}
}

// TestLiveRelaySmoke exercises a live deployed mgy-relay instance end-to-end when
// MGY_RELAY_LIVE_ENDPOINT, MGY_RELAY_LIVE_DOMAIN, and MGY_RELAY_LIVE_TOKEN are provided.
func TestLiveRelaySmoke(t *testing.T) {
	endpoint := strings.TrimSpace(os.Getenv("MGY_RELAY_LIVE_ENDPOINT"))
	domain := strings.TrimSpace(os.Getenv("MGY_RELAY_LIVE_DOMAIN"))
	token := strings.TrimSpace(os.Getenv("MGY_RELAY_LIVE_TOKEN"))
	if endpoint == "" || domain == "" || token == "" {
		t.Skip("live relay smoke test skipped (set MGY_RELAY_LIVE_ENDPOINT, MGY_RELAY_LIVE_DOMAIN, MGY_RELAY_LIVE_TOKEN)")
	}

	payload := make([]byte, 512*1024) // 512 KiB binary payload for integrity & throughput check
	_, _ = rand.Read(payload)
	wantHash := sha256.Sum256(payload)
	wantHashHex := hex.EncodeToString(wantHash[:])

	wsUpgrader := websocket.Upgrader{CheckOrigin: func(*http.Request) bool { return true }}
	localGW := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/healthz":
			w.Header().Set("Content-Type", "application/json")
			_, _ = fmt.Fprintf(w, `{"status":"ok","relay":"%s","cf_ip":"%s"}`, r.Header.Get("X-Mgy-Relay"), r.Header.Get("CF-Connecting-IP"))
		case "/blob":
			w.Header().Set("Content-Type", "application/octet-stream")
			_, _ = w.Write(payload)
		case "/ws/echo":
			conn, err := wsUpgrader.Upgrade(w, r, nil)
			if err != nil {
				return
			}
			defer conn.Close()
			for {
				mt, msg, err := conn.ReadMessage()
				if err != nil {
					return
				}
				if err := conn.WriteMessage(mt, append([]byte("live-echo:"), msg...)); err != nil {
					return
				}
			}
		default:
			http.NotFound(w, r)
		}
	}))
	defer localGW.Close()

	connected := make(chan struct{}, 1)
	client, err := NewClient(ClientConfig{
		RelayEndpoint: endpoint,
		Token:         token,
		LocalAddr:     strings.TrimPrefix(localGW.URL, "http://"),
		PublicURL:     "https://" + domain,
		Subdomain:     domain,
		OnConnected: func() {
			select {
			case connected <- struct{}{}:
			default:
			}
		},
	})
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	if err := client.Start(ctx); err != nil {
		t.Fatalf("client.Start: %v", err)
	}
	defer client.Stop()

	select {
	case <-connected:
	case <-time.After(15 * time.Second):
		t.Fatalf("timed out connecting to live relay %s", endpoint)
	}
	time.Sleep(300 * time.Millisecond)

	httpClient := &http.Client{Timeout: 20 * time.Second}

	// 1. Live HTTPS /healthz round-trip
	t0 := time.Now()
	resp, err := httpClient.Get("https://" + domain + "/healthz")
	if err != nil {
		t.Fatalf("live GET /healthz failed: %v", err)
	}
	body, _ := io.ReadAll(resp.Body)
	resp.Body.Close()
	if resp.StatusCode != http.StatusOK || !strings.Contains(string(body), `"relay":"1"`) {
		t.Fatalf("unexpected live /healthz: HTTP %d body=%s", resp.StatusCode, string(body))
	}
	t.Logf("LIVE HTTP /healthz OK in %dms: %s", time.Since(t0).Milliseconds(), string(body))

	// 2. Live 512 KiB binary transfer + SHA-256 verification
	t1 := time.Now()
	blobResp, err := httpClient.Get("https://" + domain + "/blob")
	if err != nil {
		t.Fatalf("live GET /blob failed: %v", err)
	}
	gotBlob, _ := io.ReadAll(blobResp.Body)
	blobResp.Body.Close()
	gotHash := sha256.Sum256(gotBlob)
	if hex.EncodeToString(gotHash[:]) != wantHashHex {
		t.Fatalf("512 KiB SHA-256 mismatch (len=%d)", len(gotBlob))
	}
	t.Logf("LIVE 512 KiB binary transfer SHA-256 MATCH in %dms", time.Since(t1).Milliseconds())

	// 3. 10 concurrent multiplexed HTTP requests
	t2 := time.Now()
	var wg sync.WaitGroup
	errCh := make(chan error, 10)
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(idx int) {
			defer wg.Done()
			r, err := httpClient.Get("https://" + domain + "/healthz")
			if err != nil {
				errCh <- fmt.Errorf("req %d: %w", idx, err)
				return
			}
			_, _ = io.Copy(io.Discard, r.Body)
			r.Body.Close()
			if r.StatusCode != http.StatusOK {
				errCh <- fmt.Errorf("req %d: HTTP %d", idx, r.StatusCode)
			}
		}(i)
	}
	wg.Wait()
	close(errCh)
	for e := range errCh {
		t.Fatalf("concurrent HTTP failure: %v", e)
	}
	t.Logf("LIVE 10 concurrent multiplexed HTTP requests OK in %dms", time.Since(t2).Milliseconds())

	// 4. Live full-duplex WSS echo over Cloudflare Edge -> LAX VPS -> yamux -> local server
	t3 := time.Now()
	pubWS, _, err := websocket.DefaultDialer.Dial("wss://"+domain+"/ws/echo", nil)
	if err != nil {
		t.Fatalf("live WSS dial failed: %v", err)
	}
	defer pubWS.Close()
	for i := 0; i < 3; i++ {
		msg := fmt.Sprintf("ping-%d", i)
		tMsg := time.Now()
		if err := pubWS.WriteMessage(websocket.TextMessage, []byte(msg)); err != nil {
			t.Fatalf("live WSS write: %v", err)
		}
		_, echoed, err := pubWS.ReadMessage()
		if err != nil {
			t.Fatalf("live WSS read: %v", err)
		}
		if string(echoed) != "live-echo:"+msg {
			t.Fatalf("unexpected live WSS echo: %q", string(echoed))
		}
		t.Logf("LIVE WSS frame #%d round-trip OK in %dms", i+1, time.Since(tMsg).Milliseconds())
	}
	t.Logf("LIVE WSS 3-frame test total %dms", time.Since(t3).Milliseconds())
}
