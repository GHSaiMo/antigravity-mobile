  // Browser language detection:
  // zh* -> zh-CN, ja* -> ja, en* or any other language -> en.
  function detectSystemLanguage() {
    try {
      const navLangs = (typeof navigator !== "undefined" && navigator.languages && navigator.languages.length)
        ? navigator.languages
        : [(typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || ""];
      const primary = String(navLangs[0] || "").toLowerCase().trim();
      if (primary.startsWith("zh")) {
        return "zh-CN";
      }
      if (primary.startsWith("ja")) {
        return "ja";
      }
      return "en";
    } catch (_) {
      return "en";
    }
  }

  function manifestHrefForLang(lang) {
    if (lang === "zh-CN") return "/manifest.json";
    if (lang === "ja") return "/manifest-ja.json";
    return "/manifest-en.json";
  }

  function formatRelativeTime(dateStr) {
    if (!dateStr) return "";
    const diff = (Date.now() - new Date(dateStr).getTime()) / 1000;
    if (diff < 60) {
      if (activeLang === "ja") return "たった今";
      return activeLang === "en" ? "Just now" : "刚刚";
    }
    if (diff < 3600) {
      const m = Math.floor(diff / 60);
      if (activeLang === "ja") return `${m}分前`;
      return activeLang === "en" ? `${m}m ago` : `${m}分钟前`;
    }
    if (diff < 86400) {
      const h = Math.floor(diff / 3600);
      if (activeLang === "ja") return `${h}時間前`;
      return activeLang === "en" ? `${h}h ago` : `${h}小时前`;
    }
    if (diff < 604800) {
      const d = Math.floor(diff / 86400);
      if (activeLang === "ja") return `${d}日前`;
      return activeLang === "en" ? `${d}d ago` : `${d}天前`;
    }
    const dt = new Date(dateStr);
    if (activeLang === "en") {
      const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
      return `${months[dt.getMonth()]} ${dt.getDate()}`;
    }
    return `${dt.getMonth() + 1}月${dt.getDate()}日`;
  }

