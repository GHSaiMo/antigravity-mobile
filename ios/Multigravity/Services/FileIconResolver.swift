    private static let lineSuffixRegex = try? NSRegularExpression(pattern: #":(?:L?\d+(?:-[a-zA-Z]?\d+)?|\d+(?::\d+)?)$"#)

    /// Resolves the asset image name for a given file name, path, or URL.
    public static func resolveIcon(for pathOrName: String) -> String? {
        var str = pathOrName.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !str.isEmpty else { return nil }

        // Strip enclosing backticks or quotes: `foo.swift`, "foo.swift", 'foo.swift'
        str = str.trimmingCharacters(in: CharacterSet(charactersIn: "`'\""))

        // Strip URL scheme if present (e.g. file:///path/to/file.go -> /path/to/file.go)
        if str.hasPrefix("file://") {
            str = String(str.dropFirst(7))
        } else if let schemeRange = str.range(of: #"^[a-zA-Z][a-zA-Z0-9+-.]*://"#, options: .regularExpression) {
            str = String(str[schemeRange.upperBound...])
        }

        // Strip URL fragments (#L173-L179, #anchor)
        if let hashIdx = str.firstIndex(of: "#") {
            str = String(str[..<hashIdx])
        }

        // Strip URL query parameters (?foo=bar)
        if let queryIdx = str.firstIndex(of: "?") {
            str = String(str[..<queryIdx])
        }

        // Strip trailing line/column specifiers (e.g. :123, :123:45, :L123-L145)
        if let regex = lineSuffixRegex {
            let nsStr = str as NSString
            let range = NSRange(location: 0, length: nsStr.length)
            if let match = regex.firstMatch(in: str, range: range) {
                str = nsStr.substring(to: match.range.location)
            }
        }

        str = str.trimmingCharacters(in: CharacterSet(charactersIn: "`'\" \t\n\r"))
        guard !str.isEmpty else { return nil }

        let fileName = (str as NSString).lastPathComponent.lowercased()
        if let icon = fileNames[fileName] {
            return icon
        }

        let ext = (fileName as NSString).pathExtension.lowercased()
        if !ext.isEmpty, let icon = fileExtensions[ext] {
            return icon
        }

        return nil
    }

    private static let imageExtensionsSet: Set<String> = [
        "png", "jpg", "jpeg", "webp", "gif", "heic", "heif", "bmp", "svg", "ico", "tiff", "tif"
    ]

    /// Checks whether a given path, URL or filename represents an image format.
    public static func isImage(for pathOrName: String) -> Bool {
        var str = pathOrName.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !str.isEmpty else { return false }
        str = str.trimmingCharacters(in: CharacterSet(charactersIn: "`'\""))
        if let hashIdx = str.firstIndex(of: "#") { str = String(str[..<hashIdx]) }
        if let queryIdx = str.firstIndex(of: "?") { str = String(str[..<queryIdx]) }
        let ext = (str as NSString).pathExtension.lowercased()
        return imageExtensionsSet.contains(ext)
    }

    private static func hexColor(_ hex: UInt32) -> Color {
        Color(
            .sRGB,
            red: Double((hex >> 16) & 0xff) / 255.0,
            green: Double((hex >> 8) & 0xff) / 255.0,
            blue: Double(hex & 0xff) / 255.0,
            opacity: 1.0
        )
    }

    public static func resolve(for tagOrPath: String) -> FileTypeInfo {
        var str = tagOrPath.trimmingCharacters(in: .whitespacesAndNewlines)
        if str.hasPrefix("`") && str.hasSuffix("`") { str = String(str.dropFirst().dropLast()) }
        if str.hasPrefix("file://") { str = String(str.dropFirst(7)) }
        if let hashIdx = str.firstIndex(of: "#") { str = String(str[..<hashIdx]) }
        if let queryIdx = str.firstIndex(of: "?") { str = String(str[..<queryIdx]) }
        
        let lower = str.lowercased()
        let filename = (lower as NSString).lastPathComponent
        
        if let special = specialCodeBlockNames[filename] {
            return special
        }
        
        let ext = (filename as NSString).pathExtension.isEmpty ? filename : (filename as NSString).pathExtension
        if let mapped = extensionColorMap[ext] {
            return mapped
        }
        
        return FileTypeInfo(displayName: str.uppercased(), color: Color(white: 0.6))
    }

